_LIST_COLUMNS = frozenset({"tags", "genres", "source_names"})

#: Where a pre-lowered, indexed column exists, string comparison uses it so the
#: index is still usable. Otherwise the compiler falls back to LOWER().
_CI_COLUMNS = {
    ("torrents", "name"): "t.name_lower",
    ("torrents", "category"): "t.category_lower",
}


def _sql_type_to_field_type(column: str, declared: str) -> FieldType:
    if column in _BOOLEAN_COLUMNS:
        return FieldType.BOOL
    if column in _LIST_COLUMNS:
        return FieldType.LIST
    declared = declared.upper()
    if declared in {"INTEGER", "REAL"}:
        return FieldType.NUMBER
    return FieldType.STRING


def _introspect(table: str) -> list[tuple[str, str, bool]]:
    """(column, declared type, nullable) for one snapshot table."""
    conn = sqlite3.connect(":memory:")
    try:
        create_schema(conn)
        rows = conn.execute(f"PRAGMA table_info({table})").fetchall()
    finally:
        conn.close()
    return [(r[1], r[2], not r[3]) for r in rows]


def _build_group(
    *,
    table: str,
    alias: str,
    prefix: str,
    group: str,
    docs: dict[str, tuple[str, str, str]],
    joins: tuple[str, ...] = (),
) -> list[FieldDef]:
    fields: list[FieldDef] = []
    for column, declared, nullable in _introspect(table):
        if column in _HIDDEN_COLUMNS:
            continue
        field_type = _sql_type_to_field_type(column, declared)
        label, description, sample = docs.get(
            column,
            (
                column.replace("_", " ").capitalize(),
                f"{table}.{column}",
                "",
            ),
        )
        expr = f"{alias}.{column}"
        fields.append(
            FieldDef(
                key=f"{prefix}.{column}",
                label=label,
                type=field_type,
                group=group,
                description=description,
                sample=sample,
                expr=expr,
                joins=joins,
                ci_expr=_CI_COLUMNS.get((table, column)),
                nullable=nullable,
                is_token_list=column in _LIST_COLUMNS,
            )
        )
    return fields


def _storage_fields() -> list[FieldDef]:
    """Storage columns, each taking the path's name as an argument.

    Compiles to a scalar subquery so ``storage["downloads"].used_percent > 85``
    reads as one comparison rather than forcing the user to write a join.
    """
    fields: list[FieldDef] = []
    for column, declared, _ in _introspect("storage_paths"):
        if column in _HIDDEN_COLUMNS or column in {"name", "path", "error", "filesystem",
                                                   "mountpoint", "used_bytes", "free_bytes",
                                                   "total_bytes", "folder_size_bytes"}:
            continue
        label, description, sample = _STORAGE_DOCS.get(
            column, (column.replace("_", " ").capitalize(), f"storage_paths.{column}", "")
        )
        fields.append(
            FieldDef(
                key=f"storage.{column}",
                label=label,
                type=_sql_type_to_field_type(column, declared),
                group="Storage",
                description=description,
                sample=sample,
                expr=f"(SELECT sp.{column} FROM storage_paths sp WHERE sp.name_key = ?)",
                qualifier_label="Storage path name",
                nullable=True,
            )
        )
    return fields


