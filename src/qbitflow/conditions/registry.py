"""Every field a condition can use, derived from the snapshot schema itself.

The list is generated by introspecting a freshly created snapshot database and
the UDF registry, then enriched with authored labels and descriptions. That
ordering matters: a hand-maintained list drifts the moment a column is added or
renamed, and the field reference panel starts advertising fields that do not
exist. Here, a column that loses its documentation still appears (with a
generated description), and a documented field whose column has gone is caught by
a test.

The registry is the single contract between the engine and the UI. The visual
builder's dropdown, the field reference panel, the SQL compiler's type rules and
the raw-SQL autocomplete all read from it.
"""

from __future__ import annotations

import sqlite3
