#: Alias for the driving table in every compiled query.
TORRENT_ALIAS = "t"

#: Joins a field may require, by name. Emitted at most once each, in this order.
JOINS: dict[str, str] = {
    "media": "LEFT JOIN media_items m ON m.id = t.media_item_id",
    "play": "LEFT JOIN play_counts pc ON pc.media_item_id = t.media_item_id",
}


@dataclass(frozen=True, slots=True)
class FieldDef:
    key: str
    label: str
    type: FieldType
    group: str
    description: str
    sample: str
    #: SQL expression this field compiles to, already qualified with its alias.
    expr: str
    joins: tuple[str, ...] = ()
    #: Expression to use for case-insensitive string comparison, when a
    #: pre-lowered indexed column exists.
    ci_expr: str | None = None
    #: When set, the field takes an argument -- for example a storage path name --
    #: and ``expr`` contains one placeholder for it.
    qualifier_label: str | None = None
    nullable: bool = False
    #: Comma-wrapped list columns are tested with a token match, not LIKE.
    is_token_list: bool = False

    @property
    def comparison_expr(self) -> str:
        return self.ci_expr or self.expr

    @property
    def takes_qualifier(self) -> bool:
        return self.qualifier_label is not None


