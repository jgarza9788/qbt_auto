@dataclass(frozen=True, slots=True)
class FieldRegistry:
    fields: dict[str, FieldDef] = field(default_factory=dict)

    def get(self, key: str) -> FieldDef | None:
        return self.fields.get(key)

    def by_group(self) -> dict[str, list[FieldDef]]:
        grouped: dict[str, list[FieldDef]] = {}
        for definition in self.fields.values():
            grouped.setdefault(definition.group, []).append(definition)
        for items in grouped.values():
            items.sort(key=lambda f: f.label.lower())
        return dict(sorted(grouped.items()))

    def operators_for(self, field_type: FieldType) -> list[ConditionOperator]:
        return list(OPERATORS_BY_TYPE.get(field_type, ()))


#: Which operators the UI offers per field type. Served to the browser rather
#: than duplicated in JavaScript, so the two cannot drift apart.
OPERATORS_BY_TYPE: dict[FieldType, tuple[ConditionOperator, ...]] = {
    FieldType.NUMBER: (
        ConditionOperator.EQ,
        ConditionOperator.NEQ,
        ConditionOperator.GT,
        ConditionOperator.GTE,
        ConditionOperator.LT,
        ConditionOperator.LTE,
        ConditionOperator.IN_LIST,
        ConditionOperator.IS_NULL,
        ConditionOperator.IS_NOT_NULL,
    ),
    FieldType.STRING: (
        ConditionOperator.EQ,
        ConditionOperator.NEQ,
        ConditionOperator.CONTAINS,
        ConditionOperator.NOT_CONTAINS,
        ConditionOperator.STARTS_WITH,
        ConditionOperator.ENDS_WITH,
        ConditionOperator.MATCHES,
        ConditionOperator.NOT_MATCHES,
        ConditionOperator.IN_LIST,
        ConditionOperator.NOT_IN_LIST,
        ConditionOperator.IS_NULL,
        ConditionOperator.IS_NOT_NULL,
    ),
    FieldType.BOOL: (ConditionOperator.IS_TRUE, ConditionOperator.IS_FALSE),
    FieldType.LIST: (
        ConditionOperator.CONTAINS,
        ConditionOperator.NOT_CONTAINS,
        ConditionOperator.IN_LIST,
        ConditionOperator.NOT_IN_LIST,
    ),
    FieldType.DATETIME: (
        ConditionOperator.OLDER_THAN_DAYS,
        ConditionOperator.NEWER_THAN_DAYS,
        ConditionOperator.IS_NULL,
        ConditionOperator.IS_NOT_NULL,
    ),
    FieldType.DURATION: (
        ConditionOperator.GT,
        ConditionOperator.GTE,
        ConditionOperator.LT,
        ConditionOperator.LTE,
    ),
}


@lru_cache(maxsize=1)
def get_registry() -> FieldRegistry:
    definitions: list[FieldDef] = []
    definitions += _build_group(
        table="torrents", alias="t", prefix="torrent", group="Torrent", docs=_TORRENT_DOCS
    )
    definitions += _build_group(
        table="media_items",
        alias="m",
        prefix="media",
        group="Media",
        docs=_MEDIA_DOCS,
        joins=("media",),
    )
    definitions += _build_group(
        table="play_counts",
        alias="pc",
        prefix="plays",
        group="Watch history",
        docs=_PLAY_DOCS,
        joins=("play",),
    )
    definitions += _storage_fields()
    definitions += _aggregate_fields()
    return FieldRegistry({d.key: d for d in definitions})


def helper_functions() -> dict[str, str]:
    """The UDFs a raw-SQL condition may call, for the reference panel."""
    return dict(FUNCTION_DOCS)
